    <h2>What is an affiliate link?</h2>
    <p>
        An affiliate link is a special URL that includes a tracking code. When you click one and complete
        a purchase, the retailer knows the sale came from MoltDeals and pays a small referral fee
        (typically 1–10% of the sale value). <strong>The retailer pays this — not you.</strong>
        Your price is identical to visiting the store directly.
    </p>

